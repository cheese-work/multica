// CHE-8956: the OR between the two EXISTS arms of MarkStartedPREventsDelivered
// is not a semi-join the planner can build. It plans each arm as a correlated
// SubPlan, or as a hashed SubPlan that reads every pr.event receipt on each tick
// (CHE-7518 saw 3 to 11 s per 30 s tick; CD run 44847749497 saw 18 s on C00,
// over the 15 s quiescence threshold). Which one the planner picks flips with
// table statistics and cache state, so the test asserts the plan shape that does
// not depend on that choice: no SubPlan at all, and the receipt index in use.
// The fixture holds the C00 ratios the CHE-7518 plan recorded: 1,600 open events
// across kinds, about 160,000 receipts at about 1.4 kB each, 90% pr.event, one
// wakeup with 13,000 receipts.
const (
	planEvents             = 1600
	planHeavyWakeReceipts  = 13000
	planNeedsReceiptsEach  = 84 // pr_needs_attention wakeups: pr.event receipts
	planChecksReceiptsEach = 10 // pr_checks_failed wakeups: pr.checks_failed receipts
)

func seedMarkStartedPlan(ctx context.Context, t *testing.T, tx pgx.Tx) string {
	t.Helper()
	var ws string
	if err := tx.QueryRow(ctx, `INSERT INTO workspace (name, slug, issue_prefix) VALUES ('che8956', 'che8956-plan', 'C89') RETURNING id::text`).Scan(&ws); err != nil {
		t.Fatal(err)
	}
	seed := []string{
		`CREATE TEMP TABLE plan_issue ON COMMIT DROP AS SELECT gen_random_uuid() id, gen_random_uuid() pr, g FROM generate_series(1, $2::int) g`,
		`INSERT INTO github_pull_request (id, workspace_id, installation_id, repo_owner, repo_name, pr_number, title, state, html_url, pr_created_at, pr_updated_at, head_sha, head_repo_same)
		 SELECT pr, $1::uuid, 1, 'acme', 'widget', g, 't', 'open', 'u', now(), now(), 'h1', true FROM plan_issue`,
		// Open events no wake carries: they stay open and are re-checked on every tick.
		`INSERT INTO issue_pr_event (workspace_id, issue_id, pull_request_id, kind, head_sha, base_sha, observed_at, dedupe_key, status)
		 SELECT $1::uuid, id, pr, (ARRAY['checks_failed', 'conflict', 'head_changed'])[1 + g % 3], 'h' || g, 'b', now(), 'd' || g,
		        (ARRAY['accepted', 'next_turn', 'notified'])[1 + g % 3]
		 FROM plan_issue`,
		`INSERT INTO issue_wakeup (id, workspace_id, issue_id, instruction, kind, mode, system_rule)
		 SELECT gen_random_uuid(), $1::uuid, i.id, 'x', 'event', 'continuous', r
		 FROM plan_issue i, unnest(ARRAY['pr_needs_attention', 'pr_checks_failed']) r`,
		`CREATE TEMP TABLE plan_task ON COMMIT DROP AS SELECT gen_random_uuid() id`,
		`INSERT INTO agent (id, workspace_id, name, runtime_mode) VALUES (gen_random_uuid(), $1::uuid, 'plan', 'local')`,
		`INSERT INTO agent_task_queue (id, agent_id, status, started_at, completed_at)
		 SELECT t.id, (SELECT id FROM agent WHERE workspace_id = $1::uuid), 'completed', now(), now() FROM plan_task t`,
		// pr.event receipts: 84 per pr_needs_attention wakeup, plus one wakeup
		// (the first issue's) holding 13,000. Every one names the issue's open
		// event and none names a run: production receipts are mostly processed
		// without a task (paused, skipped, coalesced), and CHE-8960 saw 143
		// receipts per event, about 198,000 in all, each probing
		// agent_task_queue to match none.
		`INSERT INTO issue_wakeup_receipt (id, wakeup_id, revision, event_key, event_type, payload, task_id, processed_at)
		 SELECT gen_random_uuid(), w.id, 1, 'k' || k, 'pr.event',
		        jsonb_build_object('event_id', (SELECT e.id::text FROM issue_pr_event e WHERE e.issue_id = i.id), 'head_sha', 'z' || k, 'repo_owner', 'acme', 'repo_name', 'widget', 'pr_number', '1',
		                           'detail', (SELECT string_agg(md5(random()::text || g), '') FROM generate_series(1, 45) g WHERE k > 0)),
		        NULL, now()
		 FROM issue_wakeup w
		 JOIN plan_issue i ON i.id = w.issue_id AND w.system_rule = 'pr_needs_attention'
		 JOIN LATERAL generate_series(1, CASE WHEN i.g = 1 THEN $4::int ELSE $3::int END) k ON true
		 WHERE w.workspace_id = $1::uuid`,
		`INSERT INTO issue_wakeup_receipt (id, wakeup_id, revision, event_key, event_type, payload, task_id, processed_at)
		 SELECT gen_random_uuid(), w.id, 1, 'k' || k, 'pr.checks_failed',
		        jsonb_build_object('head_sha', 'z' || k, 'repo_owner', 'acme', 'repo_name', 'widget', 'pr_number', '1',
		                           'detail', (SELECT string_agg(md5(random()::text || g), '') FROM generate_series(1, 45) g WHERE k > 0)),
		        (SELECT id FROM plan_task), now()
		 FROM issue_wakeup w, generate_series(1, $5::int) k
		 WHERE w.workspace_id = $1::uuid AND w.system_rule = 'pr_checks_failed'`,
	}
	// The workspace id is generated by the database and the counts are constants.
	fill := strings.NewReplacer(
		"$1::uuid", "'"+ws+"'::uuid",
		"$2::int", strconv.Itoa(planEvents),
		"$3::int", strconv.Itoa(planNeedsReceiptsEach),
		"$4::int", strconv.Itoa(planHeavyWakeReceipts),
		"$5::int", strconv.Itoa(planChecksReceiptsEach),
	)
	for _, statement := range seed {
		statement = fill.Replace(statement)
		if _, err := tx.Exec(ctx, statement); err != nil {
			t.Fatalf("seed: %v\n%s", err, statement)
		}
	}
	for _, table := range []string{"issue_pr_event", "issue_wakeup", "issue_wakeup_receipt", "github_pull_request", "agent_task_queue"} {
		if _, err := tx.Exec(ctx, "ANALYZE "+table); err != nil {
			t.Fatal(err)
		}
	}
	return ws
}

// plainPlan returns the text of EXPLAIN (no ANALYZE) of the statement with the
// production argument: workspace_ids NULL, as the wakeup Tick passes it.
func plainPlan(ctx context.Context, t *testing.T, tx pgx.Tx, sql string) string {
	t.Helper()
	rows, err := tx.Query(ctx, "EXPLAIN "+sql, []pgtype.UUID(nil))
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var plan strings.Builder
	for rows.Next() {
		var line string
		if err := rows.Scan(&line); err != nil {
			t.Fatal(err)
		}
		plan.WriteString(line + "\n")
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	return plan.String()
}

func TestMarkStartedPREventsDeliveredPlanUsesReceiptIndexes(t *testing.T) {
	ctx, tx := oracleTx(t)
	seedMarkStartedPlan(ctx, t, tx)

	plan := plainPlan(ctx, t, tx, markStartedPREventsDelivered)
	t.Logf("plan:\n%s", plan)
	if strings.Contains(plan, "SubPlan") {
		t.Errorf("plan holds a SubPlan: the OR of EXISTS arms cannot be a semi-join, and a hashed SubPlan reads every pr.event receipt each tick\n%s", plan)
	}
	for _, line := range strings.Split(plan, "\n") {
		if strings.Contains(line, "Seq Scan on issue_wakeup_receipt") {
			t.Errorf("plan scans issue_wakeup_receipt in full: %s\n%s", strings.TrimSpace(line), plan)
		}
	}
	// The partial index holds only receipts that name a run; the full
	// (event_id, wakeup_id) index would read every receipt of the event.
	if !strings.Contains(plan, "idx_issue_wakeup_receipt_pr_event_id_task") {
		t.Errorf("plan does not use idx_issue_wakeup_receipt_pr_event_id_task\n%s", plan)
	}
	if strings.Contains(plan, "using idx_issue_wakeup_receipt_pr_event_id on") {
		t.Errorf("plan reads the full receipt event_id index, which holds receipts that name no run\n%s", plan)
	}

	work, raw, err := explainOracle(ctx, tx, markStartedPREventsDelivered, []pgtype.UUID(nil))
	if err != nil {
		t.Fatal(err)
	}
	// The unindexed plan reads every receipt (about 150,000 rows). Per open event
	// the indexed plan probes each index once: bound 25 rows and 60 buffers per
	// event, far under a scan.
	t.Logf("rows examined %d, buffers %d\n%s", work.rowsExamined, work.buffers, raw)
	if limit := int64(planEvents * 25); work.rowsExamined > limit {
		t.Errorf("rows examined %d, want at most %d", work.rowsExamined, limit)
	}
	if limit := int64(planEvents * 60); work.buffers > limit {
		t.Errorf("shared buffers %d, want at most %d", work.buffers, limit)
	}
}

// Negative control: the OR form on the same fixture plans as SubPlans, so the
// shape assertion above can tell the two forms apart.
func TestMarkStartedPREventsDeliveredOrFormPlansSubPlans(t *testing.T) {
	ctx, tx := oracleTx(t)
	seedMarkStartedPlan(ctx, t, tx)
	const orForm = `UPDATE issue_pr_event e SET status = 'delivered' FROM github_pull_request pr
WHERE pr.id = e.pull_request_id AND e.status IN ('accepted', 'next_turn', 'notified')
  AND ($1::uuid[] IS NULL OR e.workspace_id = ANY($1::uuid[]))
  AND (EXISTS (SELECT 1 FROM issue_wakeup w JOIN issue_wakeup_receipt r ON r.wakeup_id = w.id JOIN agent_task_queue t ON t.id = r.task_id
      WHERE w.issue_id = e.issue_id AND w.system_rule = 'pr_needs_attention' AND r.event_type = 'pr.event'
        AND r.payload->>'event_id' = e.id::text AND t.started_at IS NOT NULL)
   OR EXISTS (SELECT 1 FROM issue_wakeup lw JOIN issue_wakeup_receipt lr ON lr.wakeup_id = lw.id JOIN agent_task_queue lt ON lt.id = lr.task_id
      WHERE lw.issue_id = e.issue_id AND lr.payload->>'head_sha' = e.head_sha AND lt.started_at IS NOT NULL))`
	plan := plainPlan(ctx, t, tx, orForm)
	if !strings.Contains(plan, "SubPlan") {
		t.Errorf("the OR form no longer plans as SubPlans on this fixture, so the shape assertion proves nothing\n%s", plan)
	}
}

type markStartedCase struct {
	name       string
	kind       string
	status     string
	rule       string // issue_wakeup.system_rule
	recType    string // receipt event_type
	payload    string // payload; %[1]s event id, %[2]s head, %[3]s base, %[4]s repo, %[4]s = repo
	otherIssue bool   // the wakeup belongs to another issue
	notStarted bool
	want       string // status after the call
}

func TestMarkStartedPREventsDeliveredBehavior(t *testing.T) {
	ctx, tx := oracleTx(t)
	var ws string
	if err := tx.QueryRow(ctx, `INSERT INTO workspace (name, slug, issue_prefix) VALUES ('che8956b', 'che8956-behavior', 'C8B') RETURNING id::text`).Scan(&ws); err != nil {
		t.Fatal(err)
	}
	for _, s := range []string{
		`INSERT INTO agent (id, workspace_id, name, runtime_mode) VALUES (gen_random_uuid(), '` + ws + `', 'beh', 'local')`,
	} {
		if _, err := tx.Exec(ctx, s); err != nil {
			t.Fatal(err)
		}
	}
	var started, queued string
	for _, q := range []struct {
		dst *string
		sql string
	}{
		{&started, `INSERT INTO agent_task_queue (id, agent_id, status, started_at, completed_at) VALUES (gen_random_uuid(), (SELECT id FROM agent WHERE workspace_id = '` + ws + `'), 'completed', now(), now()) RETURNING id::text`},
		{&queued, `INSERT INTO agent_task_queue (id, agent_id, status, completed_at) VALUES (gen_random_uuid(), (SELECT id FROM agent WHERE workspace_id = '` + ws + `'), 'cancelled', now()) RETURNING id::text`},
	} {
		if err := tx.QueryRow(ctx, q.sql).Scan(q.dst); err != nil {
			t.Fatal(err)
		}
	}

	const legacyPayload = `"head_sha":"%[2]s","repo_owner":"acme","repo_name":"%[4]s","pr_number":"7"`
	cases := []markStartedCase{
		{name: "pr.event arm delivers", kind: "checks_failed", status: "next_turn", rule: "pr_needs_attention", recType: "pr.event", payload: `"event_id":"%[1]s"`, want: "delivered"},
		{name: "pr.event arm covers any kind", kind: "head_changed", status: "accepted", rule: "pr_needs_attention", recType: "pr.event", payload: `"event_id":"%[1]s"`, want: "delivered"},
		{name: "pr.event arm covers notified", kind: "conflict", status: "notified", rule: "pr_needs_attention", recType: "pr.event", payload: `"event_id":"%[1]s"`, want: "delivered"},
		{name: "pr.event arm needs a started run", kind: "checks_failed", status: "next_turn", rule: "pr_needs_attention", recType: "pr.event", payload: `"event_id":"%[1]s"`, notStarted: true, want: "next_turn"},
		{name: "pr.event arm needs the pr_needs_attention rule", kind: "checks_failed", status: "next_turn", rule: "pr_checks_failed", recType: "pr.event", payload: `"event_id":"%[1]s"`, want: "next_turn"},
		{name: "pr.event arm needs the same issue", kind: "checks_failed", status: "next_turn", rule: "pr_needs_attention", recType: "pr.event", payload: `"event_id":"%[1]s"`, otherIssue: true, want: "next_turn"},
		{name: "pr.event receipt of another event", kind: "checks_failed", status: "next_turn", rule: "pr_needs_attention", recType: "pr.event", payload: `"event_id":"%[1]s9"`, want: "next_turn"},
		{name: "delivering event is not overwritten", kind: "checks_failed", status: "delivering", rule: "pr_needs_attention", recType: "pr.event", payload: `"event_id":"%[1]s"`, want: "delivering"},
		{name: "legacy checks_failed arm delivers", kind: "checks_failed", status: "next_turn", rule: "pr_checks_failed", recType: "pr.checks_failed", payload: legacyPayload, want: "delivered"},
		{name: "legacy checks_failed needs the same head", kind: "checks_failed", status: "next_turn", rule: "pr_checks_failed", recType: "pr.checks_failed", payload: `"head_sha":"other","repo_owner":"acme","repo_name":"%[4]s","pr_number":"7"`, want: "next_turn"},
		{name: "legacy checks_failed needs the same pull request", kind: "checks_failed", status: "next_turn", rule: "pr_checks_failed", recType: "pr.checks_failed", payload: `"head_sha":"%[2]s","repo_owner":"acme","repo_name":"%[4]s","pr_number":"8"`, want: "next_turn"},
		{name: "legacy checks_failed needs a started run", kind: "checks_failed", status: "next_turn", rule: "pr_checks_failed", recType: "pr.checks_failed", payload: legacyPayload, notStarted: true, want: "next_turn"},
		{name: "legacy checks_failed needs its rule", kind: "checks_failed", status: "next_turn", rule: "pr_needs_attention", recType: "pr.checks_failed", payload: legacyPayload, want: "next_turn"},
		{name: "legacy checks_failed needs the same issue", kind: "checks_failed", status: "next_turn", rule: "pr_checks_failed", recType: "pr.checks_failed", payload: legacyPayload, otherIssue: true, want: "next_turn"},
		{name: "legacy conflict arm delivers", kind: "conflict", status: "next_turn", rule: "pr_needs_attention", recType: "pr.mergeability", payload: legacyPayload + `,"merge_state":"DIRTY","base_sha":"%[3]s"`, want: "delivered"},
		{name: "legacy conflict needs DIRTY", kind: "conflict", status: "next_turn", rule: "pr_needs_attention", recType: "pr.mergeability", payload: legacyPayload + `,"merge_state":"CLEAN","base_sha":"%[3]s"`, want: "next_turn"},
		{name: "legacy conflict needs the same base", kind: "conflict", status: "next_turn", rule: "pr_needs_attention", recType: "pr.mergeability", payload: legacyPayload + `,"merge_state":"DIRTY","base_sha":"moved"`, want: "next_turn"},
		{name: "legacy conflict needs a started run", kind: "conflict", status: "next_turn", rule: "pr_needs_attention", recType: "pr.mergeability", payload: legacyPayload + `,"merge_state":"DIRTY","base_sha":"%[3]s"`, notStarted: true, want: "next_turn"},
		{name: "head_changed event ignores a legacy receipt", kind: "head_changed", status: "next_turn", rule: "pr_checks_failed", recType: "pr.checks_failed", payload: legacyPayload, want: "next_turn"},
		{name: "checks_failed event ignores a conflict receipt", kind: "checks_failed", status: "next_turn", rule: "pr_needs_attention", recType: "pr.mergeability", payload: legacyPayload + `,"merge_state":"DIRTY","base_sha":"%[3]s"`, want: "next_turn"},
	}

	ids := make([]string, len(cases))
	for i, c := range cases {
		var issueID, otherID, prID string
		if err := tx.QueryRow(ctx, `SELECT gen_random_uuid()::text, gen_random_uuid()::text, gen_random_uuid()::text`).Scan(&issueID, &otherID, &prID); err != nil {
			t.Fatal(err)
		}
		head, base, repo := fmt.Sprintf("head%d", i), fmt.Sprintf("base%d", i), fmt.Sprintf("widget%d", i)
		if _, err := tx.Exec(ctx, `INSERT INTO github_pull_request (id, workspace_id, installation_id, repo_owner, repo_name, pr_number, title, state, html_url, pr_created_at, pr_updated_at, head_sha, head_repo_same)
			VALUES ($1, $2, 1, 'acme', $4, 7, 't', 'open', 'u', now(), now(), $3, true)`, prID, ws, head, repo); err != nil {
			t.Fatalf("%s: pr: %v", c.name, err)
		}
		if err := tx.QueryRow(ctx, `INSERT INTO issue_pr_event (workspace_id, issue_id, pull_request_id, kind, head_sha, base_sha, observed_at, dedupe_key, status)
			VALUES ($1, $2, $3, $4, $5, $6, now(), 'd', $7) RETURNING id::text`, ws, issueID, prID, c.kind, head, base, c.status).Scan(&ids[i]); err != nil {
			t.Fatalf("%s: event: %v", c.name, err)
		}
		wakeIssue := issueID
		if c.otherIssue {
			wakeIssue = otherID
		}
		var wakeID string
		if err := tx.QueryRow(ctx, `INSERT INTO issue_wakeup (id, workspace_id, issue_id, instruction, kind, mode, system_rule)
			VALUES (gen_random_uuid(), $1, $2, 'x', 'event', 'continuous', $3) RETURNING id::text`, ws, wakeIssue, c.rule).Scan(&wakeID); err != nil {
			t.Fatalf("%s: wakeup: %v", c.name, err)
		}
		task := started
		if c.notStarted {
			task = queued
		}
		payload := "{" + fmt.Sprintf(c.payload, ids[i], head, base, repo) + "}"
		if _, err := tx.Exec(ctx, `INSERT INTO issue_wakeup_receipt (id, wakeup_id, revision, event_key, event_type, payload, task_id, processed_at)
			VALUES (gen_random_uuid(), $1, 1, 'k', $2, $3::jsonb, $4, now())`, wakeID, c.recType, payload, task); err != nil {
			t.Fatalf("%s: receipt: %v", c.name, err)
		}
	}

	// The workspace filter: an event of another workspace is left alone.
	var other pgtype.UUID
	if err := other.Scan("00000000-0000-0000-0000-0000000000aa"); err != nil {
		t.Fatal(err)
	}
	q := New(tx)
	n, err := q.MarkStartedPREventsDelivered(ctx, []pgtype.UUID{other})
	if err != nil || n != 0 {
		t.Fatalf("filter on another workspace: rows %d, err %v; want 0", n, err)
	}

	wantDelivered := int64(0)
	for _, c := range cases {
		if c.want == "delivered" {
			wantDelivered++
		}
	}
	got, err := q.MarkStartedPREventsDelivered(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	if got != wantDelivered {
		t.Errorf("rows updated %d, want %d", got, wantDelivered)
	}
	for i, c := range cases {
		var status string
		if err := tx.QueryRow(ctx, `SELECT status FROM issue_pr_event WHERE id = $1`, ids[i]).Scan(&status); err != nil {
			t.Fatal(err)
		}
		if status != c.want {
			t.Errorf("%s: status %q, want %q", c.name, status, c.want)
		}
	}
	// A second pass changes nothing.
	if again, err := q.MarkStartedPREventsDelivered(ctx, nil); err != nil || again != 0 {
		t.Errorf("second pass: rows %d, err %v; want 0", again, err)
	}
}
