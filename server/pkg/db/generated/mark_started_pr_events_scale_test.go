package db

import (
	"context"
	"encoding/json"
	"os"
	"strconv"
	"strings"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
)

// CHE-6728: MarkStartedPREventsDelivered ran past the 15 s deploy quiescence
// threshold on C00. Every stuck event re-read every receipt of its issue's
// wakeups and filtered the payload in memory. The cost is read in buffers, not
// seconds, so the test does not depend on the host's speed.
func TestMarkStartedPREventsDeliveredReadsBoundedBuffers(t *testing.T) {
	const (
		issues           = 1000
		eventsPerIssue   = 5
		receiptsPerWake  = 150
		maxSharedBuffers = 150000 // the unindexed plan reads about 1500000
	)
	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		dsn = "postgres://multica:multica@localhost:5432/multica?sslmode=disable"
	}
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	pool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Skip(err)
	}
	defer pool.Close()
	if err := pool.Ping(ctx); err != nil {
		t.Skip(err)
	}
	tx, err := pool.Begin(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback(ctx) // the seed never leaves the transaction

	var ws string
	if err := tx.QueryRow(ctx, `INSERT INTO workspace (name, slug, issue_prefix) VALUES ('che6728', 'che6728-scale', 'C67') RETURNING id::text`).Scan(&ws); err != nil {
		t.Fatal(err)
	}
	seed := []string{
		`CREATE TEMP TABLE scale_issue ON COMMIT DROP AS SELECT gen_random_uuid() id, gen_random_uuid() pr, g FROM generate_series(1, $2::int) g`,
		`INSERT INTO github_pull_request (id, workspace_id, installation_id, repo_owner, repo_name, pr_number, title, state, html_url, pr_created_at, pr_updated_at, head_sha, head_repo_same)
		 SELECT pr, $1::uuid, 1, 'acme', 'widget', g, 't', 'open', 'u', now(), now(), 'h1', true FROM scale_issue`,
		// Events no wake carries: they stay next_turn and are re-checked on every pass.
		`INSERT INTO issue_pr_event (workspace_id, issue_id, pull_request_id, kind, head_sha, base_sha, observed_at, dedupe_key, status)
		 SELECT $1::uuid, i.id, i.pr, 'checks_failed', 'h' || k, 'b', now() - (k || ' minutes')::interval, 'd' || k, 'next_turn'
		 FROM scale_issue i, generate_series(1, $3::int) k`,
		`INSERT INTO issue_wakeup (id, workspace_id, issue_id, instruction, kind, mode, system_rule)
		 SELECT gen_random_uuid(), $1::uuid, i.id, 'x', 'event', 'continuous', r
		 FROM scale_issue i, unnest(ARRAY['pr_needs_attention', 'pr_checks_failed']) r`,
		`INSERT INTO issue_wakeup_receipt (id, wakeup_id, revision, event_key, event_type, payload, processed_at)
		 SELECT gen_random_uuid(), w.id, 1, 'k' || k,
		        CASE WHEN w.system_rule = 'pr_checks_failed' THEN 'pr.checks_failed' ELSE 'pr.event' END,
		        jsonb_build_object('event_id', gen_random_uuid()::text, 'head_sha', 'z' || k, 'repo_owner', 'acme', 'repo_name', 'widget', 'pr_number', '1'),
		        now()
		 FROM issue_wakeup w, generate_series(1, $4::int) k WHERE w.workspace_id = $1::uuid`,
	}
	// The workspace id is generated by the database and the counts are constants.
	fill := strings.NewReplacer("$1::uuid", "'"+ws+"'::uuid", "$2::int", strconv.Itoa(issues), "$3::int", strconv.Itoa(eventsPerIssue), "$4::int", strconv.Itoa(receiptsPerWake))
	for _, statement := range seed {
		statement = fill.Replace(statement)
		if _, err := tx.Exec(ctx, statement); err != nil {
			t.Fatalf("seed: %v\n%s", err, statement)
		}
	}
	for _, table := range []string{"issue_pr_event", "issue_wakeup", "issue_wakeup_receipt", "github_pull_request"} {
		if _, err := tx.Exec(ctx, "ANALYZE "+table); err != nil {
			t.Fatal(err)
		}
	}

	var raw []byte
	if err := tx.QueryRow(ctx, "EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) "+markStartedPREventsDelivered, []string{ws}).Scan(&raw); err != nil {
		t.Fatal(err)
	}
	var plans []struct {
		Plan struct {
			Hit  int64 `json:"Shared Hit Blocks"`
			Read int64 `json:"Shared Read Blocks"`
		}
	}
	if err := json.Unmarshal(raw, &plans); err != nil || len(plans) != 1 {
		t.Fatalf("read plan: %v: %s", err, raw)
	}
	got := plans[0].Plan.Hit + plans[0].Plan.Read
	t.Logf("shared buffers touched: %d (limit %d)", got, maxSharedBuffers)
	if got > maxSharedBuffers {
		t.Fatalf("statement touched %d shared buffers for %d stuck events, want at most %d", got, issues*eventsPerIssue, maxSharedBuffers)
	}
}
