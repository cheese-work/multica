// CHE-6889: the first EXISTS arm of MarkStartedPREventsDelivered matches
// receipts on payload->>'event_id'. Without an expression index it reads every
// pr.event receipt once per tick (C00: 37,538 seq scans of issue_wakeup_receipt).
//
// Fixture: 200 stuck events (one per issue) and 50,000 receipts across 400
// wakeups, 125 each, none matching an event. Half are pr.event receipts, half
// pr.checks_failed receipts. Each payload carries about 1.4 kB of incompressible
// detail, so the heap is about 4 rows per page as on C00 (153,053 rows in
// 305 MB); a fixture of narrow rows makes a full scan look cheaper than the
// planner finds it in production.
const (
	oracleEvents          = 200
	oracleReceiptsPerWake = 125 // 2 wakeups per issue: 200 x 2 x 125 = 50,000 receipts
	// Indexed plan: per event one probe of the (event_id, wakeup_id) index and
	// one of the (wakeup_id, head_sha) index, plus the event and pull request
	// scans: about 9 rows per event. The bound is 15 per event (observed 1,800
	// of 3,000); the unindexed plan examines about 100,000.
	oracleMaxRowsExamined = oracleEvents * 15
	// The same plan touches about 16 buffers per event (observed 3,200 of 6,000);
	// the unindexed plan about 70 (14,500).
	oracleMaxBuffers = oracleEvents * 30
)

func seedMarkStartedOracle(ctx context.Context, t *testing.T, tx pgx.Tx) string {
	t.Helper()
	var ws string
	if err := tx.QueryRow(ctx, `INSERT INTO workspace (name, slug, issue_prefix) VALUES ('che6889', 'che6889-oracle', 'C68') RETURNING id::text`).Scan(&ws); err != nil {
		t.Fatal(err)
	}
	seed := []string{
		`CREATE TEMP TABLE oracle_issue ON COMMIT DROP AS SELECT gen_random_uuid() id, gen_random_uuid() pr, g FROM generate_series(1, $2::int) g`,
		`INSERT INTO github_pull_request (id, workspace_id, installation_id, repo_owner, repo_name, pr_number, title, state, html_url, pr_created_at, pr_updated_at, head_sha, head_repo_same)
		 SELECT pr, $1::uuid, 1, 'acme', 'widget', g, 't', 'open', 'u', now(), now(), 'h1', true FROM oracle_issue`,
		`INSERT INTO issue_pr_event (workspace_id, issue_id, pull_request_id, kind, head_sha, base_sha, observed_at, dedupe_key, status)
		 SELECT $1::uuid, id, pr, 'checks_failed', 'h1', 'b', now(), 'd' || g, 'next_turn' FROM oracle_issue`,
		`INSERT INTO issue_wakeup (id, workspace_id, issue_id, instruction, kind, mode, system_rule)
		 SELECT gen_random_uuid(), $1::uuid, i.id, 'x', 'event', 'continuous', r
		 FROM oracle_issue i, unnest(ARRAY['pr_needs_attention', 'pr_checks_failed']) r`,
		// One started run that every receipt points at, so the task join passes
		// and only the payload match can reject a receipt.
		`CREATE TEMP TABLE oracle_task ON COMMIT DROP AS SELECT gen_random_uuid() id`,
		`INSERT INTO agent (id, workspace_id, name, runtime_mode) VALUES (gen_random_uuid(), $1::uuid, 'oracle', 'local')`,
		`INSERT INTO agent_task_queue (id, agent_id, status, started_at, completed_at)
		 SELECT t.id, (SELECT id FROM agent WHERE workspace_id = $1::uuid), 'completed', now(), now() FROM oracle_task t`,
		`INSERT INTO issue_wakeup_receipt (id, wakeup_id, revision, event_key, event_type, payload, task_id, processed_at)
		 SELECT gen_random_uuid(), w.id, 1, 'k' || k,
		        CASE WHEN w.system_rule = 'pr_checks_failed' THEN 'pr.checks_failed' ELSE 'pr.event' END,
		        jsonb_build_object('head_sha', 'z' || k, 'repo_owner', 'acme', 'repo_name', 'widget', 'pr_number', '1',
		                           'detail', (SELECT string_agg(md5(random()::text || g), '') FROM generate_series(1, 45) g WHERE k > 0))
		        || CASE WHEN w.system_rule = 'pr_needs_attention' THEN jsonb_build_object('event_id', gen_random_uuid()::text) ELSE '{}'::jsonb END,
		        (SELECT id FROM oracle_task), now()
		 FROM issue_wakeup w, generate_series(1, $3::int) k WHERE w.workspace_id = $1::uuid`,
	}
	// The workspace id is generated by the database and the counts are constants.
	fill := strings.NewReplacer("$1::uuid", "'"+ws+"'::uuid", "$2::int", strconv.Itoa(oracleEvents), "$3::int", strconv.Itoa(oracleReceiptsPerWake))
	for _, statement := range seed {
		statement = fill.Replace(statement)
		if _, err := tx.Exec(ctx, statement); err != nil {
			t.Fatalf("seed: %v\n%s", err, statement)
		}
	}
	for _, table := range []string{"issue_pr_event", "issue_wakeup", "issue_wakeup_receipt", "github_pull_request", "agent_task_queue"} {
		if _, err := tx.Exec(ctx, "ANALYZE "+table); err != nil {
			t.Fatal(err)
		}
	}
	return ws
}

func TestMarkStartedPREventsDeliveredExaminesBoundedRows(t *testing.T) {
	ctx, tx := oracleTx(t)
	ws := seedMarkStartedOracle(ctx, t, tx)

	work, raw, err := explainOracle(ctx, tx, markStartedPREventsDelivered, []string{ws})
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("indexed: rows examined %d (bound %d), buffers %d (bound %d)\n%s", work.rowsExamined, oracleMaxRowsExamined, work.buffers, oracleMaxBuffers, raw)
	if work.rowsExamined > oracleMaxRowsExamined {
		t.Errorf("rows examined %d for %d stuck events and %d receipts, want at most %d", work.rowsExamined, oracleEvents, oracleEvents*2*oracleReceiptsPerWake, oracleMaxRowsExamined)
	}
	if work.buffers > oracleMaxBuffers {
		t.Errorf("shared buffers %d, want at most %d", work.buffers, oracleMaxBuffers)
	}

	// In-test negative control: the same fixture with the event_id predicate
	// made non-indexable must blow through 10x the bound, or the oracle cannot
	// tell an index from a scan.
	const indexable = `AND r.payload->>'event_id' = e.id::text`
	if !strings.Contains(markStartedPREventsDelivered, indexable) {
		t.Fatal("production SQL no longer holds the event_id predicate the control rewrites")
	}
	control := strings.Replace(markStartedPREventsDelivered, indexable, `AND (r.payload->>'event_id') || '' = e.id::text`, 1)
	controlWork, _, err := explainOracle(ctx, tx, control, []string{ws})
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("control (non-indexable): rows examined %d, buffers %d", controlWork.rowsExamined, controlWork.buffers)
	if controlWork.rowsExamined <= 10*oracleMaxRowsExamined {
		t.Errorf("control examined %d rows, want more than %d: the oracle does not separate an index from a scan", controlWork.rowsExamined, 10*oracleMaxRowsExamined)
	}
}
